#!/usr/bin/env bash
# Creates the private files the local Compose stack needs. Each developer generates their own;
# all of them are git-ignored and stay on your computer. Safe to re-run: it only creates what's
# missing.
#
#   .env                          random passwords and secrets (adds missing ones to an existing file)
#   dev/secrets/jwks.private.json ES256 key Kratos signs session JWTs with (aret-backend#3)
#   dev/secrets/jwks.public.json  matching public key the services verify them with
#
# Usage: scripts/dev-env.sh
# Needs: openssl, python3 (both preinstalled on macOS)

set -euo pipefail
cd "$(dirname "$0")/.."

# 16 random bytes → 32 hex characters (Kratos's cipher secret must be exactly 32)
random_hex() { openssl rand -hex 16; }

# ---------------------------------------------------------------- .env
# Every variable the stack needs. Existing values are kept; missing ones are added with a random
# value (so pulling a new service never breaks your .env).
VARIABLES="POSTGRES_PASSWORD KRATOS_DB_PASSWORD TRACKS_DB_PASSWORD IDENTITY_DB_PASSWORD PLACES_DB_PASSWORD \
KRATOS_COOKIE_SECRET KRATOS_CIPHER_SECRET KRATOS_WEBHOOK_SECRET RUSTFS_ACCESS_KEY RUSTFS_SECRET_KEY"

if [[ ! -e .env ]]; then
  echo "# Generated by scripts/dev-env.sh on $(date +%F). LOCAL DEVELOPMENT ONLY. Never commit." > .env
  chmod 600 .env
  echo "✓ created .env (readable only by you)"
fi
for name in $VARIABLES; do
  if ! grep -q "^${name}=" .env; then
    case "$name" in
      RUSTFS_ACCESS_KEY) value="aret-dev" ;;
      KRATOS_WEBHOOK_SECRET) value="$(random_hex)$(random_hex)" ;;  # 64 characters
      *) value="$(random_hex)" ;;
    esac
    echo "${name}=${value}" >> .env
    echo "✓ added ${name} to .env"
  fi
done
echo "✓ .env has every variable (to start over: docker compose down -v && rm .env, deletes local data)"

# ---------------------------------------------------------------- session JWT signing key
if [[ -e dev/secrets/jwks.private.json && -e dev/secrets/jwks.public.json ]]; then
  echo "✓ dev/secrets/jwks.*.json exist"
else
  mkdir -p dev/secrets
  chmod 700 dev/secrets
  # New P-256 key; openssl prints its private scalar ("priv") and public point ("pub") in hex,
  # which python turns into a JSON Web Key Set (private for Kratos, public for the services).
  KEY_TEXT="$(openssl ecparam -name prime256v1 -genkey -noout | openssl ec -text -noout 2>/dev/null)" \
  KEY_ID="aret-dev-$(date +%Y%m%d)" \
  python3 - <<'PYTHON'
import base64, json, os, re

text, key_id = os.environ["KEY_TEXT"], os.environ["KEY_ID"]

def hex_block(label: str) -> bytes:
    match = re.search(label + r":\s*((?:[0-9a-f]{2}:?\s*)+)", text)
    return bytes.fromhex(re.sub(r"[^0-9a-f]", "", match.group(1)))

private_scalar = hex_block("priv")[-32:].rjust(32, b"\0")
public_point = hex_block("pub")  # 0x04 || x || y
assert len(public_point) == 65 and public_point[0] == 4, "unexpected public key format"

def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()

public_key = {
    "kty": "EC", "crv": "P-256", "alg": "ES256", "use": "sig", "kid": key_id,
    "x": b64url(public_point[1:33]), "y": b64url(public_point[33:65]),
}
private_key = dict(public_key, d=b64url(private_scalar))

for name, key in (("private", private_key), ("public", public_key)):
    path = f"dev/secrets/jwks.{name}.json"
    with open(path, "w") as file:
        json.dump({"keys": [key]}, file, indent=2)
    os.chmod(path, 0o600 if name == "private" else 0o644)
PYTHON
  echo "✓ created dev/secrets/jwks.private.json (Kratos) and jwks.public.json (services)"
fi

echo "Next: docker compose up -d"
