//! API types and validation.

use aret_common::error::ApiError;
use serde::{Deserialize, Serialize};
use time::OffsetDateTime;
use uuid::Uuid;

/// Fewest points a track can have.
pub const MIN_POINTS: usize = 2;
/// Most points a track can have: about 28 hours at one point per second.
pub const MAX_POINTS: usize = 100_000;
/// Longest title, in characters.
pub const MAX_TITLE_CHARS: usize = 200;
/// Accepted elevation range in metres (Dead Sea shore to above Everest).
const ELEVATION_RANGE_M: std::ops::RangeInclusive<f64> = -500.0..=9_000.0;

/// One recorded GPS point.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct TrackPoint {
    /// Latitude in degrees (WGS 84).
    pub lat: f64,
    /// Longitude in degrees (WGS 84).
    pub lon: f64,
    /// Elevation in metres.
    pub ele: f64,
    /// When the point was recorded (RFC 3339).
    #[serde(with = "time::serde::rfc3339")]
    pub time: OffsetDateTime,
}

/// Body of `POST /v1/tracks`.
#[derive(Debug, Clone, Deserialize)]
pub struct NewTrack {
    /// Generated by the client, ideally a UUID v7; the same id makes the upload idempotent.
    pub id: Uuid,
    /// Optional name of the hike.
    #[serde(default)]
    pub title: String,
    /// Recorded points in time order.
    pub points: Vec<TrackPoint>,
}

/// A [`NewTrack`] that passed validation.
#[derive(Debug, Clone, PartialEq)]
pub struct ValidTrack {
    /// Track id.
    pub id: Uuid,
    /// Trimmed title.
    pub title: String,
    /// At least [`MIN_POINTS`] valid points, times never going backwards.
    pub points: Vec<TrackPoint>,
}

impl ValidTrack {
    /// Time of the first point.
    pub fn started_at(&self) -> OffsetDateTime {
        self.points[0].time
    }

    /// Time of the last point.
    pub fn ended_at(&self) -> OffsetDateTime {
        self.points[self.points.len() - 1].time
    }
}

impl TryFrom<NewTrack> for ValidTrack {
    type Error = ApiError;

    fn try_from(track: NewTrack) -> Result<Self, Self::Error> {
        if track.id.is_nil() {
            return Err(ApiError::bad_request("id must not be the nil UUID"));
        }
        let title = track.title.trim().to_owned();
        if title.chars().count() > MAX_TITLE_CHARS {
            return Err(ApiError::bad_request("title is longer than 200 characters"));
        }
        if !(MIN_POINTS..=MAX_POINTS).contains(&track.points.len()) {
            return Err(ApiError::bad_request(
                "a track needs between 2 and 100000 points",
            ));
        }
        for (index, point) in track.points.iter().enumerate() {
            validate_point(index, point)?;
        }
        if let Some(index) = track
            .points
            .windows(2)
            .position(|pair| pair[1].time < pair[0].time)
        {
            return Err(ApiError::bad_request(&format!(
                "point {} is earlier than the point before it",
                index + 1
            )));
        }
        Ok(Self {
            id: track.id,
            title,
            points: track.points,
        })
    }
}

fn validate_point(index: usize, point: &TrackPoint) -> Result<(), ApiError> {
    let valid = (-90.0..=90.0).contains(&point.lat)
        && (-180.0..=180.0).contains(&point.lon)
        && ELEVATION_RANGE_M.contains(&point.ele);
    if valid {
        Ok(())
    } else {
        Err(ApiError::bad_request(&format!(
            "point {index} has an invalid latitude, longitude or elevation"
        )))
    }
}

/// A track without its points, as listed in `GET /v1/tracks`.
#[derive(Debug, Clone, PartialEq, Serialize, sqlx::FromRow)]
pub struct TrackSummary {
    /// Track id.
    pub id: Uuid,
    /// Title, possibly empty.
    pub title: String,
    /// Time of the first point.
    #[serde(with = "time::serde::rfc3339")]
    pub started_at: OffsetDateTime,
    /// Time of the last point.
    #[serde(with = "time::serde::rfc3339")]
    pub ended_at: OffsetDateTime,
    /// Length on the ground, in metres.
    pub distance_m: f64,
    /// Total climb, in metres.
    pub ascent_m: f64,
    /// Total descent, in metres.
    pub descent_m: f64,
    /// Number of recorded points.
    pub point_count: i32,
}

/// A track with all its points, from `GET /v1/tracks/{id}`.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct TrackDetail {
    /// Summary fields.
    #[serde(flatten)]
    pub summary: TrackSummary,
    /// Every recorded point, in time order.
    pub points: Vec<TrackPoint>,
}

/// Position in the "newest first" list: the last track of a page. Opaque to clients.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct PageCursor {
    /// Start time of the last track on the previous page.
    pub started_at: OffsetDateTime,
    /// Id of that track (breaks ties between equal start times).
    pub id: Uuid,
}

impl std::fmt::Display for PageCursor {
    /// URL-safe base64 of `<unix nanoseconds>:<uuid>`.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        use base64::Engine;
        use base64::engine::general_purpose::URL_SAFE_NO_PAD;

        let raw = format!("{}:{}", self.started_at.unix_timestamp_nanos(), self.id);
        f.write_str(&URL_SAFE_NO_PAD.encode(raw))
    }
}

impl std::str::FromStr for PageCursor {
    type Err = ApiError;

    fn from_str(cursor: &str) -> Result<Self, Self::Err> {
        use base64::Engine;
        use base64::engine::general_purpose::URL_SAFE_NO_PAD;

        let invalid = || ApiError::bad_request("invalid cursor");
        let bytes: Vec<u8> = URL_SAFE_NO_PAD.decode(cursor).map_err(|_| invalid())?;
        let raw: String = String::from_utf8(bytes).map_err(|_| invalid())?;
        let (nanos, id) = raw.split_once(':').ok_or_else(invalid)?;
        let nanos: i128 = nanos.parse().map_err(|_| invalid())?;
        Ok(Self {
            started_at: OffsetDateTime::from_unix_timestamp_nanos(nanos).map_err(|_| invalid())?,
            id: id.parse().map_err(|_| invalid())?,
        })
    }
}

/// One page of `GET /v1/tracks`.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct TrackPage {
    /// Tracks, newest first.
    pub items: Vec<TrackSummary>,
    /// Pass as `cursor` to get the next page; absent on the last page.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub next_cursor: Option<String>,
}

#[cfg(test)]
mod tests {
    use super::*;

    use time::macros::datetime;

    fn point(seconds: i64, lat: f64) -> TrackPoint {
        TrackPoint {
            lat,
            lon: 10.25,
            ele: 1000.0,
            time: datetime!(2026-08-01 08:00 UTC) + time::Duration::seconds(seconds),
        }
    }

    fn new_track(points: Vec<TrackPoint>) -> NewTrack {
        NewTrack {
            id: Uuid::from_u128(1),
            title: "  Pania della Croce  ".to_owned(),
            points,
        }
    }

    #[test]
    fn accepts_a_valid_track_and_trims_the_title() {
        let track =
            ValidTrack::try_from(new_track(vec![point(0, 44.0), point(5, 44.001)])).unwrap();
        assert_eq!(track.title, "Pania della Croce");
        assert_eq!(
            track.ended_at() - track.started_at(),
            time::Duration::seconds(5)
        );
    }

    #[test]
    fn rejects_too_few_points() {
        assert!(ValidTrack::try_from(new_track(vec![point(0, 44.0)])).is_err());
    }

    #[test]
    fn rejects_an_invalid_latitude() {
        let points = vec![point(0, 44.0), point(5, 91.0)];
        assert!(ValidTrack::try_from(new_track(points)).is_err());
    }

    #[test]
    fn rejects_time_going_backwards() {
        let points = vec![point(10, 44.0), point(5, 44.001)];
        let err = ValidTrack::try_from(new_track(points)).unwrap_err();
        assert_eq!(
            err.to_string(),
            "400 Bad Request: point 1 is earlier than the point before it"
        );
    }

    #[test]
    fn rejects_the_nil_uuid() {
        let mut track = new_track(vec![point(0, 44.0), point(5, 44.001)]);
        track.id = Uuid::nil();
        assert!(ValidTrack::try_from(track).is_err());
    }
}
